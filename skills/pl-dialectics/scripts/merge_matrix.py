#!/usr/bin/env python3
"""Merge comparability.json files across languages into one matrix.

Example:
    scripts/merge_matrix.py --root studies --out studies/matrix.md
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from _common import (  # noqa: E402
    Parser,
    AXES,
    EXIT_OK,
    EXIT_PRECONDITION,
    EXIT_USAGE,
    fail,
    ok,
    studies_root,
    warn,
)


def build_parser() -> argparse.ArgumentParser:
    parser = Parser(
        prog="merge_matrix.py",
        description=(
            "Read every studies/*/comparability.json and write the cross-language matrix. "
            "Refuses to merge studies produced under different schema versions."
        ),
        epilog=(
            "examples:\n"
            "  scripts/merge_matrix.py --root studies\n"
            "  scripts/merge_matrix.py --root studies --out studies/matrix.md --csv studies/matrix.csv\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--root", default=None, help="studies directory (default: ./studies)")
    parser.add_argument("--out", default=None, help="markdown output (default: <root>/matrix.md)")
    parser.add_argument("--csv", default=None, help="long-format CSV output (default: <root>/matrix.csv)")
    return parser


def load_studies(root: Path) -> list[dict]:
    studies = []
    for path in sorted(root.glob("*/comparability.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            fail(
                "merge_matrix",
                EXIT_PRECONDITION,
                f"{path} is not valid JSON: {exc}",
                "the file was hand-edited or truncated",
                "regenerate it with scripts/validate_report.py --lang <language> --emit-json",
            )
        data["_path"] = str(path)
        studies.append(data)
    return studies


def md_escape(value: str) -> str:
    return (value or "").replace("|", "\\|").replace("\n", " ").strip()


def main(argv: list[str]) -> int:
    script = "merge_matrix"
    parser = build_parser()
    if not argv:
        parser.print_usage(sys.stderr)
        print("  hint: run with --root studies (defaults are fine)\n  run --help", file=sys.stderr)
        return EXIT_USAGE
    args = parser.parse_args(argv)

    root = studies_root(args.root)
    if not root.exists():
        fail(
            script,
            EXIT_PRECONDITION,
            f"{root} does not exist",
            "no study corpus has been created yet",
            "run scripts/init_study.py --lang <language> first",
        )
    studies = load_studies(root)
    if not studies:
        fail(
            script,
            EXIT_PRECONDITION,
            f"no comparability.json found under {root}",
            "each language needs a validated study before it can join the matrix",
            "run scripts/validate_report.py --lang <language> --emit-json",
        )

    versions = {study.get("schema_version") for study in studies}
    if len(versions) > 1:
        fail(
            script,
            EXIT_PRECONDITION,
            f"mixed schema versions: {sorted(map(str, versions))}",
            "merging different schemas would silently compare incompatible axes",
            "re-emit the older studies or pin them to the same schema version",
        )

    languages = [study.get("language") or study.get("slug") for study in studies]
    out_path = Path(args.out) if args.out else root / "matrix.md"
    csv_path = Path(args.csv) if args.csv else root / "matrix.csv"

    lines = [
        "# Cross-language matrix",
        "",
        f"Schema version {studies[0].get('schema_version')}. "
        f"Languages: {', '.join(languages)}.",
        "Generated by scripts/merge_matrix.py; regenerate instead of editing.",
        "",
        "## Axis positions",
        "",
        "| Axis | " + " | ".join(languages) + " |",
        "|------|" + "|".join("---" for _ in languages) + "|",
    ]
    for axis in AXES:
        cells = []
        for study in studies:
            entry = (study.get("axes") or {}).get(axis)
            cells.append(md_escape(entry.get("position", "—") if entry else "—"))
        label = next(
            (
                (study.get("axes") or {}).get(axis, {}).get("axis", "")
                for study in studies
                if (study.get("axes") or {}).get(axis)
            ),
            "",
        )
        lines.append(f"| {axis} {md_escape(label)} | " + " | ".join(cells) + " |")

    lines += [
        "",
        "## Study summary",
        "",
        "| Field | " + " | ".join(languages) + " |",
        "|-------|" + "|".join("---" for _ in languages) + "|",
    ]
    fields = (
        ("Era covered", lambda s: s.get("era", "")),
        ("Core contradictions", lambda s: ", ".join(s.get("core_contradictions") or [])),
        ("Qualitative jumps", lambda s: ", ".join(s.get("qualitative_jumps") or [])),
        ("Syntheses", lambda s: ", ".join(s.get("major_syntheses") or [])),
        ("New tensions", lambda s: ", ".join(s.get("new_tensions") or [])),
        ("Discovered axes", lambda s: s.get("discovered_axes", "")),
        ("Dialectical verdict", lambda s: s.get("verdict", "")),
    )
    for name, getter in fields:
        lines.append(
            f"| {name} | " + " | ".join(md_escape(getter(study)) for study in studies) + " |"
        )

    missing = [
        f"{study.get('language')}:{axis}"
        for study in studies
        for axis in AXES
        if not (study.get("axes") or {}).get(axis)
    ]
    if missing:
        warn(script, f"{len(missing)} axis cells are empty: {', '.join(missing[:8])}")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

    csv_path.parent.mkdir(parents=True, exist_ok=True)
    with csv_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(["language", "axis_id", "axis", "position", "justification", "evidence"])
        for study in studies:
            for axis in AXES:
                entry = (study.get("axes") or {}).get(axis) or {}
                writer.writerow(
                    [
                        study.get("language"),
                        axis,
                        entry.get("axis", ""),
                        entry.get("position", ""),
                        entry.get("justification", ""),
                        entry.get("evidence", ""),
                    ]
                )

    ok(f"merged {len(studies)} studies: {', '.join(languages)}")
    ok(f"  markdown: {out_path}")
    ok(f"  csv:      {csv_path}")
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
