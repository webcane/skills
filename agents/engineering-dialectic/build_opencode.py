#!/usr/bin/env python3
"""Render OpenCode V2 profiles from the canonical orchestrator and role prompts."""

import argparse
from pathlib import Path
import sys

import yaml


AGENT_DIR = Path(__file__).resolve().parent
REPO_ROOT = AGENT_DIR.parent.parent
ROLE_SOURCE = REPO_ROOT / "skills/engineering-dialectic/references/role-prompts.md"
GENERATED = "<!-- Generated by build_opencode.py; edit canonical sources. -->"
ROLES = {
    "dialectic-blind-solver": ("BLIND_SOLVER", "Independently solve a neutral engineering task"),
    "dialectic-discriminator": ("DISCRIMINATOR", "Check claims against primary evidence"),
    "dialectic-role-reviewer": ("ROLE_REVIEWER", "Falsify a decision from one specified expert role"),
    "dialectic-position-advocate": ("POSITION_ADVOCATE", "Develop and challenge a known engineering option"),
}


def section(source, name):
    start = f"<!-- BEGIN {name} -->"
    end = f"<!-- END {name} -->"
    if source.count(start) != 1 or source.count(end) != 1:
        raise ValueError(f"Expected one marker pair for {name}")
    before, rest = source.split(start, 1)
    body, after = rest.split(end, 1)
    if end in before or start in after or not body.strip():
        raise ValueError(f"Invalid section {name}")
    return body.strip()


def render(model=None):
    source = (AGENT_DIR / "engineering-dialectic.md").read_text(encoding="utf-8")
    _, header, orchestrator = source.split("---", 2)
    metadata = yaml.safe_load(header)
    roles = ROLE_SOURCE.read_text(encoding="utf-8")
    common = section(roles, "COMMON")
    finding = section(roles, "FINDING_FORMAT")
    deny_all = {"action": "*", "resource": "*", "effect": "deny"}
    read_permissions = [dict(deny_all)] + [
        {"action": action, "resource": "*", "effect": "allow"}
        for action in ("read", "glob", "grep")
    ]
    read_permissions += [
        {"action": "read", "resource": pattern, "effect": "deny"}
        for pattern in ("*.env", "*.env.*")
    ]
    read_permissions.append(
        {"action": "skill", "resource": "engineering-dialectic", "effect": "allow"}
    )
    read_permissions += [
        {"action": "subagent", "resource": name, "effect": "allow"}
        for name in ROLES
    ]
    read_permissions.append({"action": "question", "resource": "*", "effect": "allow"})
    profiles = {
        "engineering-dialectic": (
            {"description": metadata["description"], "mode": "primary", "permissions": read_permissions},
            orchestrator.strip(),
        )
    }
    for name, (marker, description) in ROLES.items():
        body = common + "\n\n" + section(roles, marker)
        if marker in {"DISCRIMINATOR", "ROLE_REVIEWER"}:
            body += "\n\n" + finding
        profiles[name] = (
            {"description": description, "mode": "subagent", "permissions": [dict(deny_all)]},
            body,
        )
    result = {}
    for name, (frontmatter, body) in profiles.items():
        if model:
            frontmatter["model"] = model
        header = yaml.safe_dump(frontmatter, allow_unicode=True, sort_keys=False).strip()
        result[name + ".md"] = f"---\n{header}\n---\n\n{GENERATED}\n\n{body}\n"
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=AGENT_DIR / "adapters/opencode")
    parser.add_argument("--model", help="Verified available provider/model[#variant]; otherwise inherit")
    parser.add_argument("--check", action="store_true", help="Check generated files without writing")
    args = parser.parse_args()
    if args.model and (not args.model.strip() or "\n" in args.model):
        parser.error("model must be a non-empty single-line identifier")
    output = args.output.expanduser()
    expected = render(args.model)
    errors = []
    for name, content in expected.items():
        path = output / name
        if path.is_symlink() or (path.exists() and not path.is_file()):
            errors.append(f"Unsafe destination: {path}")
            continue
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if args.check:
            if current != content:
                errors.append(f"Missing or stale: {path}")
        elif current is not None and current != content and GENERATED not in current:
            errors.append(f"Refusing to overwrite a non-generated profile: {path}")
    if errors:
        raise SystemExit("\n".join(errors))
    if not args.check:
        output.mkdir(parents=True, exist_ok=True)
        for name, content in expected.items():
            (output / name).write_text(content, encoding="utf-8")
    print(f"{'Checked' if args.check else 'Rendered'} {len(expected)} OpenCode V2 profiles: {output}")


if __name__ == "__main__":
    main()
